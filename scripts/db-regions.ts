import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * Builds the data migration that fills public.regions with the EQuran.id provinces and regencies/cities (T9 C).
 * Sources: content/regions/equran-regions.json (the names), province-timezones.json (the zone, owned by the app) and
 * crosscheck-coordinates.json (checked against the names so a typo cannot make a region lose its coordinates).
 * Run `pnpm db:regions` to rewrite the migration, `pnpm db:regions --check` to fail when it is out of date.
 * The migration is idempotent: `on conflict (provider_region_code) do nothing`, so running it again, or after the app
 * already made a row, changes nothing. The DEMO regions of supabase/seed.sql stay as they are (mock mode and tests).
 */
const ROOT = join(import.meta.dirname, "..");
export const REGIONS_OUT = join(ROOT, "supabase", "migrations", "20261118020000_regions_equran.sql");
const SEP = "::";
const ZONES = new Set(["Asia/Jakarta", "Asia/Makassar", "Asia/Jayapura"]);

interface EquranFile {
  provinces: string[];
  regions: Record<string, string[]>;
}
interface CoordFile {
  regions: { provinsi: string; kabkota: string }[];
  unmatched?: unknown[];
}
interface TzFile {
  timezones: Record<string, string>;
}

export interface RegionRow {
  province: string;
  city: string;
  code: string;
  timezone: string;
}

/** Same id the prayer provider uses (src/server/prayer/regions.ts makeEquranRegionId), so lookups line up. */
export const regionCode = (province: string, city: string): string => `${province}${SEP}${city}`;

export function buildRegionRows(equran: EquranFile, zones: TzFile, coords: CoordFile): RegionRow[] {
  const rows: RegionRow[] = [];
  const seen = new Set<string>();
  for (const province of equran.provinces) {
    const tz = zones.timezones[province];
    if (!tz || !ZONES.has(tz)) throw new Error(`No valid timezone for province: ${province}`);
    const cities = equran.regions[province];
    if (!cities) throw new Error(`Province without regions: ${province}`);
    for (const city of cities) {
      const code = regionCode(province, city);
      if (seen.has(code)) throw new Error(`Duplicate region: ${code}`);
      seen.add(code);
      rows.push({ province, city, code, timezone: tz });
    }
  }
  for (const c of coords.regions) {
    if (!seen.has(regionCode(c.provinsi, c.kabkota))) {
      throw new Error(`Coordinates exist for a region that is not in the EQuran list: ${c.provinsi} / ${c.kabkota}`);
    }
  }
  return rows;
}

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;

export function renderMigration(rows: RegionRow[]): string {
  const values = rows.map((r) => `  (${q(r.province)}, ${q(r.city)}, ${q(r.code)}, ${q(r.timezone)})`).join(",\n");
  return `-- Generated by scripts/db-regions.ts from content/regions/*.json. Do not edit by hand: run \`pnpm db:regions\`.
-- ${rows.length} regencies and cities of the EQuran.id (Bimas Islam Kemenag RI) list. Safe to run twice.
-- provider_region_code is "<provinsi>::<kab/kota>", the same id the prayer provider uses.
insert into public.regions (province_name, city_name, provider_region_code, timezone)
values
${values}
on conflict (provider_region_code) do nothing;
`;
}

export function buildMigration(): string {
  const read = <T>(name: string): T => JSON.parse(readFileSync(join(ROOT, "content", "regions", name), "utf8")) as T;
  return renderMigration(
    buildRegionRows(read<EquranFile>("equran-regions.json"), read<TzFile>("province-timezones.json"), read<CoordFile>("crosscheck-coordinates.json")),
  );
}

function main(): void {
  const sql = buildMigration();
  if (process.argv.includes("--check")) {
    if (!existsSync(REGIONS_OUT) || readFileSync(REGIONS_OUT, "utf8") !== sql) {
      console.error("regions migration is out of date. Run: pnpm db:regions");
      process.exit(1);
    }
    console.log("regions migration is up to date");
    return;
  }
  writeFileSync(REGIONS_OUT, sql);
  console.log(`wrote ${REGIONS_OUT}`);
}

if (process.argv[1] && import.meta.filename === process.argv[1]) main();
