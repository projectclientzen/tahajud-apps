import amalan from "@content/amalan.v1.json";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { generateSeed, lit, SEED_OUT } from "../../scripts/db-seed";
import { applySeed, createTestDb } from "../../scripts/db-lib";
import { PROVISIONAL_AUTH, PROVISIONAL_SETTINGS } from "../../src/domain/config/provisional";
import { rows } from "./harness";

type RawAct = { activity_key: string; type: string; target?: number; required: boolean; dhikr_ref?: string };
const levels = amalan.levels as unknown as { level: number; night: RawAct[]; fajr: RawAct[]; post_fajr: RawAct[] }[];

describe("seed from content/amalan.v1.json", () => {
  let pg: PGlite;
  beforeAll(async () => {
    pg = await createTestDb();
  });
  afterAll(async () => pg.close());

  it("is generated, not hand copied: the committed file equals the script output", () => {
    expect(readFileSync(SEED_OUT, "utf8")).toBe(generateSeed());
    expect(readFileSync(SEED_OUT, "utf8")).toMatch(/^-- GENERATED by scripts\/db-seed\.ts/);
  });

  it.each([
    [1, 400, 5],
    [2, 1550, 9],
    [3, 1863, 11],
  ])("level %i: night dhikr total %i and %i rakaat", async (level, dhikr, rakaat) => {
    const r = await rows<{ dhikr: string; rakaat: string }>(
      pg,
      `select
         coalesce(sum(c.target_count) filter (where d.activity_type = 'dhikr' and c.required_for_completion), 0)::text as dhikr,
         coalesce(sum(c.target_count) filter (where d.activity_type = 'prayer'), 0)::text as rakaat
       from public.level_activity_config c
       join public.levels l on l.id = c.level_id
       join public.activity_definitions d on d.id = c.activity_definition_id
       where l.level_number = $1 and c.phase = 'night'`,
      [level],
    );
    expect(Number(r[0]!.dhikr)).toBe(dhikr);
    expect(Number(r[0]!.rakaat)).toBe(rakaat);
  });

  it("copies the owner's Arabic text byte for byte", async () => {
    const dhikr = amalan.dhikr as Record<string, { arabic_text: string }>;
    const db = await rows<{ activity_key: string; arabic_text: string }>(
      pg,
      "select activity_key, arabic_text from public.activity_definitions where arabic_text is not null",
    );
    expect(db.length).toBeGreaterThan(15);
    const expected = new Map<string, string>();
    for (const L of levels) {
      for (const a of [...L.night, ...L.fajr, ...L.post_fajr])
        if (a.dhikr_ref) expected.set(a.activity_key, dhikr[a.dhikr_ref]!.arabic_text);
    }
    for (const r of db) expect(r.arabic_text, r.activity_key).toBe(expected.get(r.activity_key));
    expect(db.length).toBe(expected.size);
  });

  it("leaves transliteration and meaning empty, and never invents a source classification or approval", async () => {
    const r = await rows<{ t: string; m: string; sc: string[]; rs: string[] }>(
      pg,
      `select count(transliteration)::text as t, count(meaning)::text as m,
              array_agg(distinct source_classification) as sc, array_agg(distinct review_status) as rs
       from public.activity_definitions`,
    );
    expect(Number(r[0]!.t)).toBe(0);
    expect(Number(r[0]!.m)).toBe(0);
    expect(r[0]!.sc).toEqual(["unverified"]);
    // the owner's file says "published"; nothing is "approved" by a guess
    expect(r[0]!.rs).toEqual([amalan.review_status]);
  });

  it("keeps required flags, targets, order, and phases from the file", async () => {
    const db = await rows<{
      level: number;
      phase: string;
      key: string;
      seq: number;
      req: boolean;
      target: number | null;
    }>(
      pg,
      `select l.level_number::int as level, c.phase, d.activity_key as key, c.sequence_order as seq,
              c.required_for_completion as req, c.target_count as target
       from public.level_activity_config c join public.levels l on l.id = c.level_id
       join public.activity_definitions d on d.id = c.activity_definition_id`,
    );
    let total = 0;
    for (const L of levels) {
      for (const phase of ["night", "fajr", "post_fajr"] as const) {
        L[phase].forEach((a, i) => {
          total++;
          const row = db.find((r) => r.level === L.level && r.phase === phase && r.key === a.activity_key);
          expect(row, `${L.level}/${phase}/${a.activity_key}`).toMatchObject({
            seq: i + 1,
            req: a.required,
            target: a.target ?? null,
          });
        });
      }
    }
    expect(db.length).toBe(total);
  });

  it("keeps 'tahlil' as two entries (night and after Fajr) with one definition", async () => {
    const r = await rows<{ phase: string }>(
      pg,
      `select c.phase from public.level_activity_config c
       join public.levels l on l.id = c.level_id join public.activity_definitions d on d.id = c.activity_definition_id
       where l.level_number = 1 and d.activity_key = 'tahlil' order by 1`,
    );
    expect(r.map((x) => x.phase)).toEqual(["night", "post_fajr"]);
  });

  it("stores per-level wording only when it differs (Salat Witir)", async () => {
    const r = await rows<{ level: number; override: string | null }>(
      pg,
      `select l.level_number::int as level, c.title_override as override from public.level_activity_config c
       join public.levels l on l.id = c.level_id join public.activity_definitions d on d.id = c.activity_definition_id
       where d.activity_key = 'salat_witir_1' order by 1`,
    );
    expect(r).toEqual([
      { level: 1, override: null },
      { level: 2, override: "Salat Witir (1 rakaat)" },
      { level: 3, override: "Salat Witir (1 rakaat)" },
    ]);
  });

  it("keeps the Qur'an links as positions only", async () => {
    const r = await rows<{ activity_key: string; quran_ref: Record<string, number> }>(
      pg,
      "select activity_key, quran_ref from public.activity_definitions where quran_ref is not null order by 1",
    );
    expect(r).toEqual([
      { activity_key: "pf_al_waqiah", quran_ref: { surah: 56 } },
      { activity_key: "pf_ayat_seribu_dinar", quran_ref: { surah: 65, from: 2, to: 3 } },
    ]);
    expect((await rows(pg, "select 1 from public.quran_verses")).length).toBe(0); // no Qur'an text is seeded
  });

  it("marks level targets and settings as provisional, with the values from the domain config", async () => {
    const lv = await rows<{ n: number; req: number; period: number; mins: number; prov: boolean }>(
      pg,
      `select level_number::int as n, required_successful_nights as req, suggested_period_nights as period,
              estimated_duration_minutes as mins, provisional as prov from public.levels order by 1`,
    );
    expect(lv).toEqual(
      [1, 2, 3].map((n) => ({
        n,
        req: PROVISIONAL_SETTINGS.levels[n as 1 | 2 | 3].requiredSuccessfulNights,
        period: PROVISIONAL_SETTINGS.levels[n as 1 | 2 | 3].suggestedPeriodNights,
        mins: PROVISIONAL_SETTINGS.levels[n as 1 | 2 | 3].estimatedDurationMinutes,
        prov: true,
      })),
    );
    const st = await rows<{ key: string; value: unknown; provisional: boolean }>(
      pg,
      "select key, value, provisional from public.app_settings order by 1",
    );
    const byKey = Object.fromEntries(st.map((s) => [s.key, s]));
    expect(byKey.cutoff_local_time).toMatchObject({ value: "12:00", provisional: true });
    expect(byKey.correction_window_hours).toMatchObject({ value: 48, provisional: true });
    expect(byKey.max_active_devices).toMatchObject({ value: PROVISIONAL_AUTH.maxActiveDevices, provisional: true });
    expect(byKey.notification_expiry_minutes!.value).toEqual(PROVISIONAL_SETTINGS.notificationExpiryMinutes);
    expect(st.every((s) => s.provisional)).toBe(true);
  });

  it("labels sample regions as DEMO", async () => {
    const r = await rows<{ province_name: string; city_name: string }>(
      pg,
      "select province_name, city_name from public.regions order by 2",
    );
    expect(r.length).toBe(3);
    for (const x of r) {
      expect(x.province_name).toBe("DEMO");
      expect(x.city_name).toMatch(/contoh/);
    }
  });

  it("can run twice: same rows, and an admin's setting is not overwritten", async () => {
    const count = async () =>
      (
        await rows<{ n: string }>(
          pg,
          `select (select count(*) from public.activity_definitions) || ',' || (select count(*) from public.level_activity_config) || ',' ||
                (select count(*) from public.levels) || ',' || (select count(*) from public.regions) || ',' || (select count(*) from public.app_settings) as n`,
        )
      )[0]!.n;
    const before = await count();
    await pg.query("update public.app_settings set value = '36'::jsonb where key = 'correction_window_hours'");
    await applySeed(pg);
    expect(await count()).toBe(before);
    const v = await rows<{ v: number }>(
      pg,
      "select (value #>> '{}')::int as v from public.app_settings where key = 'correction_window_hours'",
    );
    expect(v[0]!.v).toBe(36);
    await pg.query("update public.app_settings set value = '48'::jsonb where key = 'correction_window_hours'");
  });
});

describe("seed script helpers", () => {
  it("quotes any text without altering it, even text with dollar signs", async () => {
    const pg = new PGlite();
    for (const s of ["plain", "with $s$ tag", "ends with $s", "a'b\"c\\d", "عَرَبِيّ", "line\nbreak", "$$", ""]) {
      const r = await pg.query<{ v: string }>(`select ${lit(s)}::text as v`);
      expect(r.rows[0]!.v).toBe(s);
    }
    expect(lit(null)).toBe("null");
    await pg.close();
  });
});
