import { hashPhone } from "../../src/server/auth/crypto";

/**
 * Shared by the live e2e config and the live specs. TEST DATA ONLY: one phone and one password for every live user.
 * Real accounts never get a shared or default password. These exist only in the throwaway PGlite database of the run.
 */
export const LIVE_PEPPER = "e2e-pepper-e2e-pepper-e2e-pepper-123456";
export const LIVE_PHONE = "0812-3456-7890";
export const LIVE_PASSWORD = "uji-live-password-panjang";
export const LIVE_NEW_PASSWORD = "uji-live-password-pengganti";

const PROJECTS = ["mobile", "desktop"] as const;
const quote = (s: string): string => "'" + s.split("'").join("''") + "'";

/** Same format as src/server/auth/password.ts (ln=10 is the cheapest the code accepts, so the suite stays quick). */
function cheapHash(password: string): string {
  const salt = Buffer.from("live-e2e-salt-16!");
  const key = scryptSync(password.normalize("NFKC"), salt, 32, { N: 1024, r: 8, p: 1 });
  const b64 = (b: Buffer) => b.toString("base64").replace(/=+$/, "");
  return `$scrypt$ln=10,r=8,p=1$${b64(salt)}$${b64(key)}`;
}

/** Emails that have a paid, verified order and no account yet: they activate through the real endpoint. */
export const ACTIVATABLE = [
  ...["live", "live-out", "live-logout", "live-tick", "act-api", "act-ui", "reset", "chpw", "limit"].flatMap((k) =>
    PROJECTS.map((p) => `${k}-${p}@ngajigaes.test`),
  ),
  ...["quran", "prayer", "push-a", "push-b", "origin", "del"].flatMap((k) =>
    PROJECTS.map((p) => `t3c-${k}-${p}@ngajigaes.test`),
  ),
];

/** Accounts that already exist, with an entitlement that is not active (they sign in and see their status). */
export const WITH_ACCOUNT: { email: string; status: "pending_verification" | "suspended" }[] = [
  ...PROJECTS.map((p) => ({ email: `pending-${p}@ngajigaes.test`, status: "pending_verification" as const })),
  ...PROJECTS.map((p) => ({ email: `t3c-lapsed-${p}@ngajigaes.test`, status: "suspended" as const })),
];

/** SQL run after the seed by the PGlite adapter (TAHAJUD_TEST_DB_SQL). Runs as the database owner. */
export function liveAuthSql(pepper: string = LIVE_PEPPER): string {
  const phone = hashPhone(pepper, LIVE_PHONE)!;
  const hash = cheapHash(LIVE_PASSWORD);
  const lines: string[] = ["-- Generated by tests/e2e/live-auth.ts. Test emails only."];
  for (const email of ACTIVATABLE) {
    lines.push(
      `with o as (insert into public.purchase_orders (scalev_order_id, customer_email_normalized, payment_status, verified_via, payment_verified_at, customer_phone_hash)
         values (${quote(`E2E-${email}`)}, ${quote(email)}, 'paid', 'scalev_api', now(), ${quote(phone)}) returning id)
       insert into public.access_entitlements (email_normalized, status, starts_at, purchase_order_id)
       select ${quote(email)}, 'active', now() - interval '1 day', o.id from o;`,
    );
  }
  for (const { email, status } of WITH_ACCOUNT) {
    lines.push(
      `with u as (insert into auth.users (email) values (${quote(email)}) returning id),
            p as (insert into public.profiles (user_id, email_normalized) select id, ${quote(email)} from u),
            c as (insert into public.auth_credentials (user_id, password_hash, password_changed_at) select id, ${quote(hash)}, now() from u)
       insert into public.access_entitlements (user_id, email_normalized, status, starts_at)
       select u.id, ${quote(email)}, ${quote(status)}, now() - interval '1 day' from u;`,
    );
  }
  return lines.join("\n");
}
