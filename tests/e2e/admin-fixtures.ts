import { scryptSync } from "node:crypto";
import { hashPhone } from "../../src/server/auth/crypto";
import { LIVE_PASSWORD, LIVE_PEPPER } from "./live-auth";

/**
 * Admin live e2e data. TEST DATA ONLY, in the throwaway PGlite database of the run.
 * The accounts have the shared live test password so the spec can sign in; no real account ever gets one.
 * None has an authenticator yet: each spec enrols it through the real screen.
 */
const PROJECTS = ["mobile", "desktop"] as const;
const quote = (s: string): string => "'" + s.split("'").join("''") + "'";

function cheapHash(password: string): string {
  const salt = Buffer.from("live-e2e-salt-16!");
  const key = scryptSync(password.normalize("NFKC"), salt, 32, { N: 1024, r: 8, p: 1 });
  const b64 = (b: Buffer) => b.toString("base64").replace(/=+$/, "");
  return `$scrypt$ln=10,r=8,p=1$${b64(salt)}$${b64(key)}`;
}

export const ADMIN_ROLE = { super: "super_admin", cs: "support_admin", content: "content_admin" } as const;
export const adminEmail = (kind: keyof typeof ADMIN_ROLE, project: string) => `adm-${kind}-${project}@ngajigaes.test`;
export const buyerEmail = (project: string) => `adm-buyer-${project}@ngajigaes.test`;
export const staffEmail = (project: string) => `adm-staff-${project}@ngajigaes.test`;
export const BUYER_PHONE = "0812-5555-0101";
export const ORDER_NUMBER = (project: string) => `ADMQ-${project.toUpperCase()}`;

export function adminSql(pepper: string = LIVE_PEPPER): string {
  const hash = cheapHash(LIVE_PASSWORD);
  const lines = ["-- Generated by tests/e2e/admin-fixtures.ts. Test emails only."];
  for (const p of PROJECTS) {
    for (const kind of Object.keys(ADMIN_ROLE) as (keyof typeof ADMIN_ROLE)[]) {
      const email = adminEmail(kind, p);
      lines.push(
        `with u as (insert into auth.users (email) values (${quote(email)}) returning id),
              pr as (insert into public.profiles (user_id, email_normalized) select id, ${quote(email)} from u),
              c as (insert into public.auth_credentials (user_id, password_hash, password_changed_at) select id, ${quote(hash)}, now() from u)
         insert into public.user_roles (user_id, role) select id, ${quote(ADMIN_ROLE[kind])} from u;`,
      );
    }
    // A paid order held back by the worker (spam flag): no entitlement until an admin approves it.
    lines.push(
      `insert into public.purchase_orders (scalev_order_id, scalev_order_number, customer_email_normalized, payment_status, verified_via,
         payment_verified_at, customer_phone_hash, quarantine_reason, amount, buyer_name)
       values (${quote(`E2E-ADM-Q-${p}`)}, ${quote(ORDER_NUMBER(p))}, ${quote(buyerEmail(p))}, 'paid', 'scalev_api', now(),
         ${quote(hashPhone(pepper, BUYER_PHONE)!)}, 'spam_flag', 99000, 'Pembeli Uji');`,
    );
  }
  return lines.join("\n");
}
